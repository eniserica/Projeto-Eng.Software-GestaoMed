CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash TEXT NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('paciente', 'medico', 'administrador')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_lower_unique
    ON usuarios (LOWER(email));

CREATE TABLE IF NOT EXISTS pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
    cpf VARCHAR(11) UNIQUE,
    telefone VARCHAR(20),
    data_nascimento DATE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS medicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
    crm VARCHAR(30) UNIQUE,
    especialidade VARCHAR(120),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS consultas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL REFERENCES pacientes(id),
    medico_id BIGINT NOT NULL REFERENCES medicos(id),
    inicio TIMESTAMPTZ NOT NULL,
    duracao_minutos SMALLINT NOT NULL DEFAULT 30 CHECK (duracao_minutos > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'agendada'
        CHECK (status IN ('agendada', 'confirmada', 'concluida', 'cancelada')),
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS consultas_paciente_inicio_idx
    ON consultas (paciente_id, inicio);
CREATE INDEX IF NOT EXISTS consultas_medico_inicio_idx
    ON consultas (medico_id, inicio);

CREATE TABLE IF NOT EXISTS prontuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL UNIQUE REFERENCES consultas(id),
    diagnostico TEXT NOT NULL,
    tratamento TEXT,
    notas TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS exames (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT REFERENCES consultas(id) ON DELETE SET NULL,
    paciente_id BIGINT NOT NULL REFERENCES pacientes(id),
    medico_id BIGINT NOT NULL REFERENCES medicos(id),
    descricao VARCHAR(300) NOT NULL,
    arquivo_url TEXT,
    resultado TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'solicitado'
        CHECK (status IN ('solicitado', 'em_andamento', 'concluido', 'cancelado')),
    solicitado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS exames_paciente_solicitado_idx
    ON exames (paciente_id, solicitado_em DESC);
